// The blinded check: can a model tell what the simulated users wrote from a held-out set written by hand? The judge
// sees one message, or a pair of the same kind, never the arm, the persona or which set it came from, and says which
// was written by a model playing a person. Chance is 50%. A judge that can't beat chance is weak evidence that the
// persona model's messages read like the held-out ones; one that can is evidence they don't.
//   node test/sim_users/judge.mjs <run folder> [<run folder> ...] [--out file] [--n 40]
// The judge: JUDGE_LLM_URL (an A100 test endpoint, http://127.0.0.1:11448 by default), Muse Glimmer.
// Its limits (docs/simulated_users.md): the held-out set was written by an AI assistant, not by real users; the judge is
// the same model as the persona model; the sets are small.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { stream, shuffle } from "./rng.mjs";
import { wilson } from "./metrics.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const URL_ = (process.env.JUDGE_LLM_URL || "http://127.0.0.1:11448").replace(/\/+$/, "");
if (/:(11434|11435)\b/.test(URL_)) throw new Error("never the live model server");
const arg = (k, d) => { const i = process.argv.indexOf(`--${k}`); return i > 0 ? process.argv[i + 1] : d; };
const N = +arg("n", 40);
const KINDS = { hello: "hello", request: "request", question: "question", bail: "bail", "checkin-reply": "checkin-reply", log: "log", idea: "idea", "feed-post": "post", "feed-comment": "comment", "trash-talk": "trash-talk" };

async function ask(messages, schema) {
  for (let k = 0; k < 3; k++) {
    try {
      const r = await fetch(`${URL_}/api/chat`, { method: "POST", headers: { "content-type": "application/json" }, signal: AbortSignal.timeout(120000),
        body: JSON.stringify({ model: "muse-glimmer", messages, stream: false, think: "low", format: schema, options: { num_predict: 900, temperature: 0 } }) });
      const v = JSON.parse((await r.json()).message?.content || "null");
      if (v) return v;
    } catch { /* again */ }
  }
  return null;
}
const SYS = "You check a dataset of short chat messages that people send to a sports club's chat assistant on Messenger (English, Traditional Chinese, or both). Some were written by people and some were generated by a language model asked to play a person. Judge from the text alone.";

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dirs = process.argv.slice(2).filter((a, i, all) => !a.startsWith("--") && !["--out", "--n"].includes(all[i - 1]));
  const held = JSON.parse(fs.readFileSync(path.join(HERE, "judge_heldout.json"), "utf8")).messages;
  const gen = [];
  for (const d of dirs) {
    const s = JSON.parse(fs.readFileSync(path.join(d, "serve.json"), "utf8")).st;
    for (const u of Object.values(s)) for (const a of u.actions) if (KINDS[a.what] && a.text && !a.text.startsWith("/")) gen.push({ kind: KINDS[a.what], text: a.text });
  }
  const r = stream(11, "judge");
  const byKind = (xs) => xs.reduce((o, x) => ((o[x.kind] ||= []).push(x), o), {});
  const G = byKind(shuffle(r, [...new Map(gen.map((x) => [x.text, x])).values()])), Hd = byKind(shuffle(r, held));
  // pairs of the same kind, one from each set, in a random order; and the singles from both sets
  const pairs = [];
  for (const k of Object.keys(Hd)) for (let i = 0; i < Math.min(Hd[k].length, (G[k] || []).length); i++) pairs.push(r() < 0.5 ? { a: G[k][i], b: Hd[k][i], model: "A" } : { a: Hd[k][i], b: G[k][i], model: "B" });
  const pick = shuffle(r, pairs).slice(0, N);
  const singles = shuffle(r, [...pick.map((p) => ({ ...(p.model === "A" ? p.a : p.b), from: "model" })), ...pick.map((p) => ({ ...(p.model === "A" ? p.b : p.a), from: "person" }))]);
  const out = { pairs: { n: 0, right: 0 }, singles: { n: 0, right: 0, saidModel: 0 }, rows: [] };
  for (const p of pick) {
    const v = await ask([{ role: "system", content: SYS }, { role: "user", content: `Two messages of the same kind (${p.a.kind}). Exactly one was generated by a language model playing a person.\nA: ${p.a.text}\nB: ${p.b.text}\nWhich one did the model write? JSON: {"model": "A" | "B"}` }], { type: "object", properties: { model: { enum: ["A", "B"] } }, required: ["model"] });
    if (!v) continue;
    out.pairs.n++; if (v.model === p.model) out.pairs.right++;
    out.rows.push({ kind: p.a.kind, a: p.a.text, b: p.b.text, model: p.model, said: v.model });
  }
  for (const s of singles) {
    const v = await ask([{ role: "system", content: SYS }, { role: "user", content: `Message (${s.kind}): ${s.text}\nWas it written by a person or generated by a language model playing a person? JSON: {"by": "person" | "model"}` }], { type: "object", properties: { by: { enum: ["person", "model"] } }, required: ["by"] });
    if (!v) continue;
    out.singles.n++; if (v.by === s.from) out.singles.right++; if (v.by === "model") out.singles.saidModel++;
  }
  const res = { simulated: true, judge: `muse-glimmer at ${URL_}`, generated: gen.length, heldout: held.length,
    pairs: { ...out.pairs, accuracy: out.pairs.n ? +(out.pairs.right / out.pairs.n).toFixed(2) : null, ci: wilson(out.pairs.right, out.pairs.n) },
    singles: { ...out.singles, accuracy: out.singles.n ? +(out.singles.right / out.singles.n).toFixed(2) : null, ci: wilson(out.singles.right, out.singles.n), saidModelShare: out.singles.n ? +(out.singles.saidModel / out.singles.n).toFixed(2) : null },
    limits: ["The held-out set was written by an AI assistant imitating people, not by real users.", "The judge is the same model (Muse Glimmer) as the persona model, so it may share its blind spots.", `Small sets: ${pick.length} pairs.`, "Chance is 0.5; an interval that includes 0.5 means the judge could not tell the sets apart."],
    rows: out.rows };
  if (arg("out")) fs.writeFileSync(path.resolve(arg("out")), JSON.stringify(res, null, 1) + "\n");
  console.log(JSON.stringify({ ...res, rows: undefined }, null, 1));
}
