// Demo reviews for the made-up town (data/reviews-seed.json), generated deterministically so the demo is the same on
// every machine. Every one is marked `seed: true` and shown as demo data. Most are by other people in town ("guest_N");
// a few are by the demo's own players, so a group can include someone who disliked a venue.
//   node scripts/seed-reviews.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

let x = 20261030;
const rand = () => { x |= 0; x = (x + 0x6d2b79f5) | 0; let t = Math.imul(x ^ (x >>> 15), 1 | x); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
const pick = (xs) => xs[Math.floor(rand() * xs.length)];

// each venue's character: its usual stars, what people tend to like and not, how many reviews
const VENUES = {
  riverside: { acts: ["badminton", "tennis", "pickleball", "basketball"], mean: 4.3, liked: ["equipment", "staff", "ontime"], disliked: ["quiet"], n: 24 },
  north: { acts: ["badminton", "basketball", "volleyball"], mean: 4.0, liked: ["space", "value"], disliked: ["clean"], n: 18 },
  lakeside: { acts: ["badminton", "pickleball"], mean: 3.6, liked: ["value"], disliked: ["equipment", "access"], n: 11 },
  midtown: { acts: ["badminton", "tennis", "table tennis"], mean: 4.6, liked: ["clean", "staff", "equipment"], disliked: ["value"], n: 29 },
  westgate: { acts: ["badminton"], mean: 3.4, liked: ["value"], disliked: ["equipment", "clean"], n: 15 },
  echo: { acts: ["karaoke"], mean: 4.4, liked: ["atmosphere", "equipment"], disliked: ["quiet"], n: 21 },
  lockbox: { acts: ["escape room"], mean: 4.7, liked: ["staff", "atmosphere"], disliked: [], n: 17 },
  dice: { acts: ["board games"], mean: 4.2, liked: ["staff", "atmosphere", "food"], disliked: ["space"], n: 13 },
  lakegrill: { acts: ["bbq"], mean: 3.9, liked: ["space", "atmosphere"], disliked: ["clean"], n: 9 },
  potluck: { acts: ["hot pot"], mean: 4.1, liked: ["food", "value"], disliked: ["quiet", "ontime"], n: 14 },
};
const SAY = {
  liked: { clean: "Spotless.", staff: "Staff were lovely.", value: "Great price for what you get.", equipment: "Everything in good shape.", space: "Plenty of room for the group.", access: "Easy to get to.", quiet: "Nice and quiet.", ontime: "Ready on time, no waiting.", food: "The food was great.", atmosphere: "Great vibe." },
  disliked: { clean: "Could be cleaner.", staff: "Staff weren't helpful.", value: "A bit pricey.", equipment: "Some of the gear is worn out.", space: "Cramped for a group.", access: "Hard to get to, parking is a pain.", quiet: "Loud.", ontime: "We waited to get started.", food: "Food was meh.", atmosphere: "No atmosphere." },
};
const DAY = 864e5, NOW = Date.parse("2026-10-30T12:00:00Z");
const reviews = [];
let guest = 1;
for (const [id, v] of Object.entries(VENUES)) {
  for (let i = 0; i < v.n; i++) {
    const stars = Math.max(1, Math.min(5, Math.round(v.mean + (rand() - 0.5) * 2.2)));
    const liked = v.liked.filter(() => rand() < (stars >= 4 ? 0.7 : 0.35)), disliked = v.disliked.filter(() => rand() < (stars <= 3 ? 0.8 : 0.3));
    const text = [...liked.map((a) => SAY.liked[a]), ...disliked.map((a) => SAY.disliked[a])].join(" ");
    reviews.push({ id: `seed_${id}_${i}`, venue: id, activity: pick(v.acts), booking: null, player: `guest_${guest++}`, stars, liked, disliked, text, at: new Date(NOW - Math.floor(rand() * 330) * DAY).toISOString(), seed: true });
  }
}
// a few by the demo's own players: Hana and Kenji had a bad time at Westgate and Lakeside; Yuki liked Midtown
for (const [player, venue, activity, stars, liked, disliked, ago] of [["hana", "westgate", "badminton", 2, [], ["equipment", "clean"], 40], ["kenji", "lakeside", "badminton", 2, [], ["access"], 75], ["yuki", "midtown", "badminton", 5, ["clean", "staff"], [], 20]])
  reviews.push({ id: `seed_${player}_${venue}`, venue, activity, booking: null, player, stars, liked, disliked, text: [...liked.map((a) => SAY.liked[a]), ...disliked.map((a) => SAY.disliked[a])].join(" "), at: new Date(NOW - ago * DAY).toISOString(), seed: true });

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "../data/reviews-seed.json");
fs.writeFileSync(out, JSON.stringify({ note: "Demo reviews for the made-up town, generated by scripts/seed-reviews.mjs. Not real people's reviews; shown as demo data.", reviews }, null, 1));
console.log(`${reviews.length} demo reviews -> ${out}`);
