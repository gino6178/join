// The Club page's Ideas tab: what the club asked its agents for and could not get, grouped by code into ideas. An idea
// is shown once 5 or more members ask for it; it becomes a proposal when weekday and weekend players both do. Members
// vote with quadratic credits (9 a month; n votes on one idea cost n²). Every idea shows where it stands, and a refused
// or rolled-back one says why. Shipped ideas are posted as club notes.
import { useCallback, useEffect, useState } from "react";
import Icon from "../components/Icon.jsx";
import { loop } from "./api.js";
import { StatusPill, statusOf, Loading, Failed, Empty, ago } from "./parts.jsx";
import "./loop.css";

const VOTABLE = new Set(["open", "review"]); // voting closes once a maintainer or the rules decide
const rank = (c) => (VOTABLE.has(c.status) ? 0 : ["approved", "building", "gated"].includes(c.status) ? 1 : c.status === "shipped" ? 2 : 3);
// where an idea stands, so a member sees first where a vote still counts
const group = (c) => (VOTABLE.has(c.status) ? "vote" : rank(c) === 1 ? "way" : "done");
const GROUPS = [
  ["vote", "Open for votes", null],
  ["way", "On the way", "Approved, building or through the gates. Voting is closed."],
  ["done", "Decided", "Shipped, rolled back or refused, each with its reason."],
];
const plural = (n, one, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
const OTHER = { weekday: "weekend", weekend: "weekday" };

export default function Ideas() {
  const [st, setSt] = useState({ phase: "loading", data: null, error: null });
  const [said, setSaid] = useState(""); // read out after a vote
  const load = useCallback(() => {
    setSt((s) => ({ ...s, phase: "loading", error: null }));
    loop.ideas().then((data) => setSt({ phase: "ready", data, error: null }), (error) => setSt((s) => ({ ...s, phase: "error", error })));
  }, []);
  useEffect(() => { load(); }, [load]);

  if (!st.data) return st.phase === "error" ? <Failed what="The club's ideas" error={st.error} onRetry={load} /> : <Loading what="the club's ideas" />;
  const { ideas, credits, of, notes, simulated } = st.data;
  const sorted = [...ideas].sort((a, b) => rank(a) - rank(b) || b.score - a.score || b.members - a.members);
  const voted = (c, n, res) => setSt((s) => ({
    ...s,
    data: {
      ...s.data,
      credits: typeof res?.credits === "number" ? res.credits : s.data.credits + c.mine * c.mine - n * n,
      ideas: s.data.ideas.map((x) => (x.id === c.id ? { ...x, votes: x.votes + n - x.mine, mine: n } : x)),
    },
  }));

  return (
    <div className="lp-ideas">
      {simulated && <p className="lp-sim"><Icon name="info" size={18} />Simulated club: members and requests generated by code (seed {simulated.seed ?? 7})</p>}
      <p className="sr-only" aria-live="polite">{said}</p>
      <div className="lp-grid">
        <div className="lp-main">
          {notes.length > 0 && (
            <section aria-labelledby="lp-notes-h">
              <h2 id="lp-notes-h" className="panel-h">Club notes</h2>
              <ul className="lp-notes">
                {notes.map((n) => (
                  <li key={n.id}>
                    <span className="lp-note-ic" aria-hidden="true"><Icon name="check" size={18} /></span>
                    <div>
                      <p className="lp-note-h"><b>{n.text}</b>{n.at && <span className="tiny muted">{ago(n.at)}</span>}</p>
                      <p>{n.title}</p>
                    </div>
                  </li>
                ))}
              </ul>
            </section>
          )}

          <section aria-labelledby="lp-ideas-h">
            <header className="lp-h">
              <h2 id="lp-ideas-h" className="panel-h">Ideas the club shared</h2>
              <span className="tiny muted">{plural(credits, "credit")} left this month</span>
            </header>
            {st.phase === "error" && <Failed what="The latest ideas" error={st.error} onRetry={load} />}
            {sorted.length === 0
              ? <Empty title="No ideas yet">An idea shows here once 5 members have asked for it. When your agent can't help with something, it offers to share the request in its own words; nothing is shared without your yes.</Empty>
              : GROUPS.map(([g, label, note]) => {
                const xs = sorted.filter((c) => group(c) === g);
                return xs.length > 0 && (
                  <div key={g} className="lp-group">
                    <h3 className="lp-group-h">{label} <span className="muted">· {xs.length}</span></h3>
                    {note && <p className="tiny muted lp-group-note">{note}</p>}
                    <ul className="lp-list">{xs.map((c) => <Idea key={c.id} c={c} credits={credits} onVoted={voted} say={setSaid} />)}</ul>
                  </div>
                );
              })}
          </section>
        </div>

        <aside className="lp-side">
          <Credits credits={credits} of={of} />
          <section className="panel" aria-labelledby="lp-how-h">
            <h2 id="lp-how-h" className="panel-h">From an idea to the app</h2>
            <ol className="lp-how">
              <li><b>You share</b><span>When your agent can't help, it offers to share the request in its own words. Nothing is shared without your yes, and names, places and health never are.</span></li>
              <li><b>The club votes</b><span>An idea shows here once 5 members ask for it, and becomes a proposal when weekday and weekend players both do.</span></li>
              <li><b>A safety review</b><span>Code checks every change against rules no vote can change. A setting inside its range ships by itself; anything else needs the maintainer.</span></li>
              <li><b>It ships behind a flag</b><span>A few beta members get it first. If anything goes wrong, it switches itself off.</span></li>
            </ol>
            <a className="link small" href="#/maintain">Maintainer review</a>
          </section>
        </aside>
      </div>
    </div>
  );
}

function Idea({ c, credits, onVoted, say }) {
  const open = VOTABLE.has(c.status);
  const why = c.reasons.join(" ");
  const same = (t) => t.trim().toLowerCase() === c.title.trim().toLowerCase();
  const quotes = c.texts.filter((t) => !same(t)).slice(0, 2);
  const counts = [plural(c.members, "member"), c.unmet && plural(c.unmet, "unmet request"), c.wishes && plural(c.wishes, "wish", "wishes")].filter(Boolean);
  return (
    <li className={`lp-idea ${c.status}`}>
      <div className="lp-idea-top">
        <StatusPill status={c.status} />
        <span className="tiny muted">{counts.join(" · ")}</span>
      </div>
      <h4 className="lp-idea-t">{c.title}</h4>
      {quotes.length > 0 && (
        <ul className="lp-quotes" aria-label="What members said">
          {quotes.map((t) => <li key={t}>“{t}”</li>)}
        </ul>
      )}
      {c.status === "refused" && <p className="lp-reason t-bad"><b>Why it was refused</b>{why || "No reason was given."}</p>}
      {c.status === "rolledBack" && <p className="lp-reason t-warn"><b>Why it was rolled back</b>{why || "Its checks switched it off."}</p>}
      {c.status === "open" && c.groups.length === 1 && OTHER[c.groups[0]] && (
        <p className="tiny muted">Only {c.groups[0]} players so far. It becomes a proposal once {OTHER[c.groups[0]]} players ask for it too.</p>
      )}
      <div className="lp-idea-foot">
        <span className="lp-votes"><b>{c.votes}</b> {c.votes === 1 ? "vote" : "votes"}{c.mine ? <span className="muted"> · {c.mine} yours</span> : null}</span>
        {open ? <Vote c={c} credits={credits} onVoted={onVoted} say={say} /> : <span className="tiny muted">{statusOf(c.status).note}</span>}
      </div>
    </li>
  );
}

// quadratic voting: set your votes on this idea (0 to 3); the cost and what is left show before anything is cast
function Vote({ c, credits, onVoted, say }) {
  const [n, setN] = useState(c.mine);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState("");
  useEffect(() => setN(c.mine), [c.mine]);
  const pool = credits + c.mine * c.mine; // the credits this idea can use: what is left plus what is already on it
  const max = Math.min(3, Math.floor(Math.sqrt(pool)));
  const cost = n * n, after = pool - cost, changed = n !== c.mine, id = `qv-${c.id}`;
  const cast = async () => {
    setBusy(true); setErr("");
    try {
      const res = await loop.vote(c.target, n);
      onVoted(c, n, res);
      const left = typeof res?.credits === "number" ? res.credits : after;
      say(n ? `${plural(n, "vote")} on “${c.title}”. ${plural(left, "credit")} left this month.` : `Votes taken back from “${c.title}”. ${plural(left, "credit")} left this month.`);
    } catch (e) { setErr(e.message || "The vote did not go through."); }
    finally { setBusy(false); }
  };
  const label = n === 0 ? "Take back my votes" : c.mine ? `Change to ${plural(n, "vote")}` : `Cast ${plural(n, "vote")}`;
  return (
    <div className="lp-vote">
      <div className="lp-step" role="group" aria-labelledby={`${id}-l`}>
        <span id={`${id}-l`} className="sr-only">Your votes on {c.title}</span>
        <button className="icon-btn" aria-label="One vote fewer" disabled={n <= 0 || busy} onClick={() => setN(n - 1)}>−</button>
        <output aria-live="polite" aria-label={plural(n, "vote")}>{n}</output>
        <button className="icon-btn" aria-label="One vote more" disabled={n >= max || busy} onClick={() => setN(n + 1)}>+</button>
      </div>
      <p className="lp-cost" id={`${id}-c`}>
        {max === 0 ? <>No credits left this month. Take votes back from another idea to vote here.</>
          : !changed && n === 0 ? <>1 vote costs 1 credit · {plural(credits, "credit")} left</>
          : !changed ? <>Your {plural(n, "vote")} {n === 1 ? "costs" : "cost"} <b>{plural(cost, "credit")}</b></>
          : <>{plural(n, "vote")} {n === 1 ? "costs" : "cost"} <b>{plural(cost, "credit")}</b> · {after} left after</>}
        {max > 0 && n >= max && max < 3 && <span className="muted"> · {plural(n + 1, "vote")} would cost {plural((n + 1) ** 2, "credit")}</span>}
      </p>
      {changed && <button className="btn primary sm" onClick={cast} disabled={busy} aria-busy={busy} aria-describedby={`${id}-c`}>{busy ? "Casting…" : label}</button>}
      {err && <p className="err lp-full" role="alert">{err}</p>}
    </div>
  );
}

function Credits({ credits, of }) {
  const month = new Date().toLocaleString("en-GB", { month: "long" });
  return (
    <section className="panel lp-credits" aria-labelledby="lp-cr-h">
      <h2 id="lp-cr-h" className="panel-h">Your votes in {month}</h2>
      <p className="lp-credits-n"><b>{credits}</b> of {of} credits left</p>
      <span className="lp-meter" role="meter" aria-label="Credits left" aria-valuemin={0} aria-valuemax={of} aria-valuenow={credits}><i style={{ transform: `scaleX(${of ? credits / of : 0})` }} /></span>
      <table className="lp-costs">
        <caption className="sr-only">What votes on one idea cost</caption>
        <thead><tr><th scope="col">Votes on one idea</th><th scope="col">Credits</th></tr></thead>
        <tbody>{[1, 2, 3].map((v) => <tr key={v}><td>{v}</td><td>{v * v}</td></tr>)}</tbody>
      </table>
      <p className="tiny muted">Each extra vote on the same idea costs more, so a few members who care a lot can't outvote the club. Credits renew each month.</p>
    </section>
  );
}
